"""Export the sim's numbers for the browser apps (web/): the champion car's physics, actuators, teacher and race rules.

    python -m sdc.export            -> web/shared/generated/sim.json

The sim (sdc/) is the source of truth. The game (web/game) builds its MuJoCo model and actuator models from this file
instead of hand-copied numbers, so a change to the car's size, springs, motor, grip model or teacher reaches it by
re-running this script. tests/test_export.py fails while the committed file is stale.

What is exported is the car the champion (models/README.md, CHAMPION) was trained and scored in: its env46["real"]
physics switches and steering expo. Structure (which joints, tendons and actuator models exist) is still written by
hand in web/game/src/carmodel.js and sim.js; a new physics switch needs a port there too (AGENTS.md).
"""

from __future__ import annotations

import dataclasses
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHAMPION = ROOT / "models" / "e7"
OUT = ROOT / "web" / "shared" / "generated" / "sim.json"


def build() -> dict:
    meta = json.loads((CHAMPION / "metrics.json").read_text())
    env46 = meta["env46"]
    real_name = env46["real"]
    os.environ["SDC_REAL"] = real_name            # racer.TEACHER depends on it (the full-size truggy's double speed)
    from sdc.jumps import car as cr
    from sdc.jumps import env as je
    from sdc.jumps import real as rl
    from sdc.phase46 import teacher as tc
    from sdc.phase47 import racer
    from sdc.race import record as rec
    real = rl.switches(real_name)
    g = cr.geometry(real)
    tau_max, top_speed = cr.motor(real)
    r6 = lambda v: round(float(v), 6)               # noqa: E731
    return {
        "_": "Generated by `python -m sdc.export` from the sim; do not edit. tests/test_export.py checks it is current.",
        "champion": CHAMPION.name,
        "real": real_name,
        "switches": sorted(real),
        "car": dict(
            timestep=cr.TIMESTEP, substeps=cr.SUBSTEPS, steer_max=cr.STEER_MAX, tire_w=cr.TIRE_W,
            wheel_r=g["wheel_r"], corner_x=g["corner_x"], corner_y=g["corner_y"], mount_z=g["mount_z"],
            box=list(g["box"]), chassis_m=g["chassis_m"], battery_m=g["battery"][0], battery_z=g["battery"][1],
            corner_m=g["corner_m"], wheel_m=g["wheel_m"], axle_i=g["axle_i"], spring_k=g["k"], spring_c=g["c"],
            tau_max=tau_max, top_speed=top_speed, lsd=dict(cr.LSD), wheel_armature=cr.WHEEL_ARMATURE),
        "actuators": dict(expo=env46.get("expo", 0.0), brake_cap=je.BRAKE_CAP, slide_s0=je.SLIDE_S0,
                          slide_s1=je.SLIDE_S1, slide_drop=je.SLIDE_DROP, on_ground=je.ON_GROUND, min_air=je.MIN_AIR),
        "phys": dict(nominal={k: r6(v) for k, v in dataclasses.asdict(rl.Phys()).items()},
                     train={k: [r6(x) for x in v] for k, v in rl.RANGES["train"].items()},
                     gate={k: [r6(x) for x in v] for k, v in rl.RANGES["gate"].items()}),
        "teacher": dict(truggy=dict(tc.TRUGGY), racer=dict(racer.TEACHER)),
        "race": dict(laps=rec.LAPS, crash_s=rec.CRASH_S, spun_deg=rec.SPUN_DEG, spun_s=rec.SPUN_S, runup_m=rec.RUNUP_M),
    }


def text() -> str:
    return json.dumps(build(), indent=1, sort_keys=True) + "\n"


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text())
    print(f"{OUT.relative_to(ROOT)} ({json.loads(OUT.read_text())['real']})", file=sys.stderr)


if __name__ == "__main__":
    main()
